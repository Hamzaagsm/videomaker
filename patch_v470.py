STAGE_RM = base64.b64decode(STAGE_B64).decode('utf-8')


def run_stage(code, name, args, cwd):
    p = cwd / name
    p.write_text(code, encoding='utf-8')
    r = subprocess.run([sys.executable, str(p)] + [str(a) for a in args],
                       cwd=str(cwd), capture_output=True, text=True)
    print(r.stdout, end='')
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        raise SystemExit(f'{name} FAIL (exit {r.returncode}) -- patch ROK diya')


def main():
    assert HP.exists(), f'JS target nahi mila: {HP}'
    assert JP.exists(), f'Java target nahi mila: {JP}'
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        js_base = td / 'built-v469-final.html'
        js_base.write_bytes(HP.read_bytes())
        ja_base = td / 'built-v469.java'
        ja_base.write_bytes(JP.read_bytes())
        run_stage(STAGE_RM, 'stage_v470.py',
                  [js_base, td / 'built-v470-final.html', ja_base, td / 'built-v470.java'], td)
